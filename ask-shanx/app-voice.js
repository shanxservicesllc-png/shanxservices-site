  const ready=cloudReady();
  $("#status-text").textContent=ready?"Internet available":"Connection unavailable";
  $("#status-detail").textContent=ready?"Questions are sent to OVHcloud AI.":"Check your connection and try again.";
  $("#footer-context").textContent="ASK SHANX";
  $("#header-status").textContent="";
