function disclosure(label, content) {
  const details = document.createElement("details");
  const summary = document.createElement("summary");
  summary.textContent = label;
  const body = document.createElement("p");
  body.textContent = content;
  details.append(summary, body);
  return details;
}
function answerDetails(message) {
  const card = document.createElement("div");
  card.className = "answer-details";
  card.append(disclosure("Evidence", "Unverified. This answer has no independently verified sources."));
  if (message.origin === OVH_REPLY) {
    card.append(disclosure("Technical details", "Generated by OVHcloud AI Endpoints using Llama 3.3 70B Instruct."));
  } else if (message.origin === VISION_REPLY) {
    card.append(disclosure("Technical details", "Photo or video still-frame analysis by OVHcloud Mistral Small 3.2 Vision. Video motion/audio not analyzed."));
  }
  return card;
}
function render() {
  $$(".message-row").forEach(e => e.remove());
  welcome.hidden = messages.length > 0;
  messages.forEach(m => {
    const row = document.createElement("article");
    row.className = "message-row " + m.role;
    const bubble = document.createElement("div");
    bubble.className = "bubble";
    bubble.textContent = m.content;
    if (m.role==="user" && typeof m.mediaPreview==="string" && m.mediaPreview.length<160000 && m.mediaPreview.startsWith("data:image/jpeg;base64,")) {
      const photo=document.createElement("img");
      photo.src=m.mediaPreview;
      photo.alt=m.mediaKind==="video"?"Still frame from sent video":"Sent photo";
      photo.className="chat-attachment-preview";
      photo.loading="lazy";
      bubble.append(photo);
    }
    if (m.role === "user" && m.mediaExpected) {
      const hint = document.createElement("small");
      hint.className = "attached-message-label";
      hint.textContent = m.mediaKind === "video" ? "  •  One video still frame" : "  •  Photo attached";
      bubble.append(hint);
    }
    if (m.role === "assistant") {
      const avatar = document.createElement("div");
      avatar.className = "avatar"; avatar.textContent = "A";
      avatar.setAttribute("aria-label","ASK SHANX");
      row.append(avatar);
    }
    const wrap = document.createElement("div");
    wrap.className = "message-body";
    wrap.append(bubble);
    if (m.role === "assistant") {
      const actions = document.createElement("div");
      actions.className = "message-actions";
      const speak = document.createElement("button");
      speak.type="button"; speak.textContent="◖)) Read aloud";
      speak.setAttribute("aria-label", "Read answer aloud");
      speak.addEventListener("click",()=>speakText(m.content));
      const copy = document.createElement("button");
      copy.type="button"; copy.textContent="Copy";
      copy.addEventListener("click", async () => {
        try {await navigator.clipboard.writeText(m.content); copy.textContent="Copied";} catch {notify("Could not copy this answer.");}
      });
      const download=document.createElement("button");
      download.type="button";download.textContent="Download";
      download.title="Save this answer as a text file";
      download.addEventListener("click",()=>window.AskShanXExport?.answer(m.content));
      const code=window.AskShanXExport?.firstCode(m.content);
      if(code){
        const codeBtn=document.createElement("button");
        codeBtn.type="button";codeBtn.textContent="Save code";
        codeBtn.title="Save first code block as a source file";
        codeBtn.addEventListener("click",()=>window.AskShanXExport?.code(m.content));
        actions.append(speak,copy,download,codeBtn);
      }else actions.append(speak,copy,download);
      wrap.append(actions,answerDetails(m));
    }
    row.append(wrap);
    convo.append(row);
  });
  scroll.scrollTop=scroll.scrollHeight;
}
function setBusy(v) {
  busy=v;
  send.querySelector("span").textContent = v ? "Thinking…" : "Ask ShanX";
  input.disabled = v;
  newChat.disabled = v;
  clearHistory.disabled = v;
  updateSend();
}
function updateSend() {
  send.disabled = busy || !cloudReady() || (!input.value.trim() && !media?.has() && !micRequested);
  retryButton.hidden = busy || messages.at(-1)?.role !== "user";
  retryButton.disabled = !cloudReady() || (messages.at(-1)?.mediaExpected && !media?.has());
}
function resizeInput() {
  input.style.height = "auto";
  input.style.height = Math.min(135,input.scrollHeight)+"px";
}
